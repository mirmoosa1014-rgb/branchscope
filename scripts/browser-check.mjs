import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
try {
 await page.goto(process.env.BRANCHSCOPE_URL||'http://127.0.0.1:8765');
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Complete'));
 assert.equal(await page.locator('.metric').count(),4);
 assert.equal(await page.locator('#trace tr').count(),16);
 const before=await page.locator('#branch-info').textContent();
 await page.locator('#step').fill('12');await page.locator('#step').dispatchEvent('input');
 assert.notEqual(await page.locator('#branch-info').textContent(),before);
 await page.selectOption('#workload','xor');await page.locator('#seed').fill('103');
 await page.getByRole('button',{name:'RUN TRACE'}).click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('seed 103'));
 assert.match(await page.locator('#description').textContent(),/XOR/);
 const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'EXPORT THIS RUN'}).click();
 const download=await downloadPromise;const path=await download.path();const result=JSON.parse(await fs.readFile(path,'utf8'));
 assert.equal(result.workload,'xor');assert.equal(result.seed,103);
 for(const r of result.results)assert.equal(r.miss_rate,100*r.misses/r.count);
 await page.selectOption('#budget','64');await page.selectOption('#history','32');
 await page.getByRole('button',{name:'RUN TRACE'}).click();
 await page.waitForFunction(()=>!document.querySelector('#run').disabled);
 assert.match(await page.locator('.metric.perceptron').textContent(),/296 bits used/);
 await page.selectOption('#budget','256');await page.selectOption('#history','8');
 await page.selectOption('#workload','delayed');await page.locator('#seed').fill('101');await page.getByRole('button',{name:'RUN TRACE'}).click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('seed 101'));
 await fs.mkdir('docs/images',{recursive:true});
 await page.screenshot({path:'docs/images/app-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'docs/images/app-mobile.png',fullPage:true});
 await page.emulateMedia({reducedMotion:'reduce'});
 assert.equal(await page.evaluate(()=>getComputedStyle(document.documentElement).scrollBehavior),'auto');
 await page.screenshot({path:'docs/images/app-reduced-motion.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('PASS: live run, four predictors, trace rows, neuron scrubbing, changed workload/seed, JSON export, mobile overflow, reduced motion, no page errors');
} finally {await browser.close();}
